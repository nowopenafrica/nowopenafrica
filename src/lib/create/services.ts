/**
 * Reading the service catalogue — from the database, not from a constant.
 *
 * ── WHY THIS REPLACES A TYPESCRIPT ARRAY ─────────────────────────────────
 *
 * src/lib/create/catalogue.ts holds ~50 SKUs as code. It is a good model and
 * its honesty mechanism survives here intact. What it cannot do is change:
 * moving one price needs an engineer, a build and a deploy, so in practice
 * prices do not get corrected — they get worked around.
 *
 * ── THE PART THAT MATTERS MORE THAN THE SCHEMA ───────────────────────────
 *
 * `orderable` is NOT computed here. It is a generated column on the table,
 * so every reader — this file, the admin screen, a future checkout, a SQL
 * query somebody runs by hand — gets the same answer from the same place.
 *
 * That is a direct lesson from media_services: its page carried a comment
 * saying the sample rows were "gated to DEV", which was true of the writer
 * and never of the reader, and eighteen invented companies with invented
 * ratings sat on the public marketplace for a month. A rule a component can
 * forget to apply is a rule that will be forgotten.
 *
 * ── AND THE PRICE IS NOT COMPUTED HERE EITHER ────────────────────────────
 *
 * `quote()` calls the database function. The browser can display a price; it
 * must never be the thing that decides one, because anything the browser
 * decides is a number the customer can edit.
 */

import { supabase } from '../supabase';

export type PriceBasis = 'proposed' | 'indicative' | 'quoted';
export type DeliverableType = 'digital' | 'print' | 'video' | 'strategy' | 'managed';
export type Fulfilment = 'instant' | 'creator' | 'partner';

export interface ServiceCategory {
  id: string;
  slug: string;
  name: string;
  summary: string | null;
  icon: string | null;
  sort_order: number;
}

export interface Service {
  id: string;
  sku: string;
  slug: string;
  name: string;
  short_description: string | null;
  category_id: string;
  deliverable_type: DeliverableType;
  fulfilment: Fulfilment;
  pricing_model: string;
  currency: string;
  price_minor: number | null;
  price_unit: string | null;
  price_basis: PriceBasis;
  price_includes: string[];
  exclusions: string[];
  turnaround_min_days: number | null;
  turnaround_max_days: number | null;
  revisions_included: number | null;
  editable_source_included: boolean;
  available_formats: string[];
  template_tags: string[];
  production_required: boolean;
  quote_required: boolean;
  /** Generated by the database. Never recomputed in a component. */
  is_orderable: boolean;
  /*
   * Quantity breaks, ascending.
   *
   * Carried on the service rather than fetched when needed, because WITHOUT
   * them the configurator never asks for a quantity — and a tiered service
   * with no quantity cannot be priced at all. That was a real bug: the panel
   * opened, showed a figure from its own arithmetic, and the server refused
   * to price it.
   */
  tiers?: { min_quantity: number; price_minor: number }[];
  featured: boolean;
  sort_order: number;
}

const SERVICE_COLUMNS =
  'id, sku, slug, name, short_description, category_id, deliverable_type, fulfilment,'
  + ' pricing_model, currency, price_minor, price_unit, price_basis, price_includes,'
  + ' exclusions, turnaround_min_days, turnaround_max_days, revisions_included,'
  + ' editable_source_included, available_formats, template_tags, production_required,'
  + ' quote_required, is_orderable, featured, sort_order,'
  + ' service_price_tiers(min_quantity, price_minor)';

/** PostgREST returns the embedded rows under the table's own name. */
type RawService = Omit<Service, 'tiers'> & {
  service_price_tiers?: { min_quantity: number; price_minor: number }[];
};

const withTiers = (row: RawService): Service => {
  const { service_price_tiers: tiers, ...rest } = row;
  return {
    ...rest,
    /* Ascending, because every reader assumes it — tierFor() takes the last
       eligible one, which is the largest only if they are in order. */
    tiers: tiers?.length ? [...tiers].sort((a, b) => a.min_quantity - b.min_quantity) : undefined,
  };
};

/**
 * supabase-js RESOLVES with { data, error }. It does not reject.
 *
 * A `.catch()` here would never fire and a failed request would render as an
 * empty catalogue — a page that says NowOpen offers nothing, with no error
 * anywhere. So every read checks `error` explicitly.
 */
export async function loadCategories(): Promise<ServiceCategory[]> {
  const { data, error } = await supabase
    .from('service_categories')
    .select('id, slug, name, summary, icon, sort_order')
    .order('sort_order');
  if (error) throw new Error(error.message);
  return data ?? [];
}

export async function loadServices(): Promise<Service[]> {
  /*
   * PostgREST truncates every response at 1000 rows without saying so. The
   * catalogue is ~130 today, so one page is enough — but the range is
   * explicit rather than implied, so the day it is not, this fails loudly
   * instead of silently serving a partial catalogue.
   */
  const { data, error } = await supabase
    .from('services')
    .select(SERVICE_COLUMNS)
    .order('sort_order')
    .range(0, 999);
  if (error) throw new Error(error.message);
  if ((data?.length ?? 0) >= 1000) {
    throw new Error('The catalogue is larger than one page; loadServices needs paging.');
  }
  /*
   * Through `unknown`: this project does not generate Supabase types, so the
   * client cannot know a table added in a migration and infers an error shape
   * for the row. The runtime columns are the ones named in SERVICE_COLUMNS.
   */
  return ((data ?? []) as unknown as RawService[]).map(withTiers);
}

export async function loadService(slug: string): Promise<Service | null> {
  const { data, error } = await supabase
    .from('services').select(SERVICE_COLUMNS).eq('slug', slug).maybeSingle();
  if (error) throw new Error(error.message);
  return data ? withTiers(data as unknown as RawService) : null;
}

/* ── pricing ─────────────────────────────────────────────────────────────── */

export interface QuoteLine { label: string; amount: number }

export interface ServiceQuote {
  sku: string;
  service: string;
  currency: string;
  lines: QuoteLine[];
  total: number;
  basis: PriceBasis;
  orderable: boolean;
  turnaround: [number, number];
}

export interface QuoteRefusal {
  refusal: string;
  message: string;
  sku?: string;
  minimum?: number;
  maximum?: number;
  option?: string;
}

export const refused = (q: ServiceQuote | QuoteRefusal): q is QuoteRefusal =>
  'refusal' in q;

/**
 * What a configuration costs, decided by the server.
 *
 * The result is display-only. A checkout must call this again on the server
 * side and charge what IT returns — a total that travelled through a browser
 * is a total somebody could have changed.
 */
export async function quote(
  sku: string,
  quantity?: number,
  options: Record<string, string> = {},
): Promise<ServiceQuote | QuoteRefusal> {
  const { data, error } = await supabase.rpc('price_service', {
    p_sku: sku,
    p_quantity: quantity ?? null,
    p_options: options,
  });
  if (error) throw new Error(error.message);
  return data as ServiceQuote | QuoteRefusal;
}

/* ── search ──────────────────────────────────────────────────────────────── */

/** Strip to comparable words: lowercase, no punctuation, no empty parts. */
export const words = (text: string): string[] =>
  (text ?? '').toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean);

/**
 * Rank services against what somebody typed.
 *
 * Deliverable match beats keyword overlap, which is the brief's rule and the
 * difference between "I need a business card" returning business cards and
 * it returning everything with the word "business" in it — including every
 * business profile, business proposal and business card ARTWORK listing.
 */
/*
 * Words that carry no intent.
 *
 * "I need a business card" is five words and only two of them say anything.
 * Without this, "a" scored a substring hit against "restaurant menu design"
 * and a search for "drone survey of a quarry" — which this catalogue genuinely
 * cannot do — came back offering menus. A search that answers everything
 * tells you nothing, and it hides the gap that a zero-result search is
 * supposed to report.
 */
const STOP = new Set([
  'i', 'a', 'an', 'the', 'my', 'our', 'me', 'we', 'you', 'your',
  'need', 'needs', 'want', 'wants', 'looking', 'get', 'make', 'create',
  'for', 'of', 'to', 'and', 'with', 'some', 'please', 'can', 'do', 'design',
]);

/** The shortest substring worth matching on. */
const SUBSTRING_MIN = 4;

export function rankServices(
  query: string,
  services: Service[],
  synonyms: Map<string, string[]> = new Map(),
): Service[] {
  const all = words(query);
  /* Kept for the whole-phrase test below; scored on only the meaningful ones. */
  const terms = all.filter((t) => !STOP.has(t));
  if (all.length === 0) return [];

  const scored = services.map((service) => {
    const name = words(service.name);
    const phrase = name.join(' ');
    const aliases = synonyms.get(service.sku) ?? [];

    let score = 0;
    /* The whole query appearing in the name is the strongest signal there is. */
    if (terms.length > 1 && phrase.includes(terms.join(' '))) score += 100;
    for (const alias of aliases) {
      if (query.toLowerCase().includes(alias.toLowerCase())) score += 80;
    }
    for (const term of terms) {
      if (name.includes(term)) score += 10;
      /*
       * A substring only counts at real length. Anything shorter matches by
       * accident — which is how "a" scored against half the catalogue.
       */
      else if (term.length >= SUBSTRING_MIN && phrase.includes(term)) score += 4;
      if (aliases.some((a) => words(a).includes(term))) score += 6;
    }
    return { service, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score || a.service.sort_order - b.service.sort_order)
    .map((s) => s.service);
}

export async function loadSynonyms(): Promise<Map<string, string[]>> {
  const { data, error } = await supabase
    .from('service_synonyms')
    .select('term, services!inner(sku)')
    .range(0, 999);
  if (error) throw new Error(error.message);

  const out = new Map<string, string[]>();
  for (const row of (data ?? []) as { term: string; services: { sku: string } | { sku: string }[] }[]) {
    const joined = Array.isArray(row.services) ? row.services[0] : row.services;
    if (!joined?.sku) continue;
    out.set(joined.sku, [...(out.get(joined.sku) ?? []), row.term]);
  }
  return out;
}
