/**
 * Copy for one template.
 *
 * Falls back field by field, so a template with no entry renders exactly what
 * it rendered before this existed.
 */
export function sampleFor(template: Pick<DesignTemplate, 'key'>): TemplateContent {
  return { ...BASE_SAMPLE, ...(BY_KEY[template.key] ?? {}) };
}

/** How many templates carry purpose-shaped copy. For the test, and for honesty. */
export const TEMPLATES_WITH_OWN_COPY = Object.keys(BY_KEY).length;

const SAMPLE_CACHE = new Map<string, TemplateContent>();

/**
 * The template's own sample words for one row of a slot: row `index` of a
 * contact or services list, or a text role's line (index 0). Undefined when
 * the template has no such row. design/icons.ts trusts a template's per-row
 * icon hint only while the row still reads exactly this (Ruling AL).
 */
export function sampleRow(template: Pick<DesignTemplate, 'key'>, role: string, index: number): string | undefined {
  // BY_KEY never changes, so one merged copy per template serves every row of every render.
  let s = SAMPLE_CACHE.get(template.key);
  if (!s) { s = sampleFor(template); SAMPLE_CACHE.set(template.key, s); }
  if (role === 'contact') return s.contact?.[index];
  if (role === 'services') return s.services?.[index];
  if (index !== 0) return undefined;
  const v = (s as Record<string, unknown>)[role];
  return typeof v === 'string' ? v : undefined;
}

const SAMPLE_TEXTS = new Map<string, Set<string>>();
const normText = (s: string): string => s.normalize('NFC').trim().replace(/\s+/g, ' ').toLowerCase();

/**
 * Is this one of the gallery's own sample strings, in these roles (every
 * role when none are named), on any template? The no-photo monogram (Ruling
 * AW) asks about `brand` only: it is the owner's initial once the owner has
 * typed a name, so "Your brand" draws no "Y", while a real name that happens
 * to match some sample headline ("Now open") still gets its initial.
 */
export function isSampleText(text: string | undefined, roles?: readonly (keyof TemplateContent)[]): boolean {
  if (!text || !text.trim()) return false;
  const key = roles ? [...roles].sort().join(',') : '*';
  let set = SAMPLE_TEXTS.get(key);
  if (!set) {
    const found = new Set<string>();
    const add = (v: unknown) => {
      if (typeof v === 'string') found.add(normText(v));
      else if (Array.isArray(v)) v.forEach(add);
      else if (v && typeof v === 'object') Object.values(v).forEach(add);
    };
    for (const copy of [BASE_SAMPLE, ...Object.values(BY_KEY)]) {
      if (!roles) add(copy);
      else for (const r of roles) add((copy as Record<string, unknown>)[r]);
    }
    set = found;
    SAMPLE_TEXTS.set(key, set);
  }
  return set.has(normText(text));
}
