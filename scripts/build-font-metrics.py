#!/usr/bin/env python3
"""
Read the advance width of every character the composition engine sets, from
the font files the product ships, and write them as typed data.

WHY

src/lib/create/compose/canvas.ts plans a layout before a browser exists: it
decides where each line breaks and how tall each block is. It used one average
width per face, kept generous so nothing clipped. The CI-3 review showed the
cost: Bodoni Moda was estimated a quarter wider than it is, so "Good skin
takes its time." broke into three lines where two fit. Measuring the real
files removes the guess.

Kerning is not read. Pairs kern tighter far more often than looser, so a line
measured without it is at worst slightly long, which wraps early and never
clips.

USAGE (fontTools 4.66+ and the brotli module, as build-studio-fonts.py):

    python -I scripts/build-font-metrics.py

Reads src/lib/design/typefaces.ts for the files, writes
src/lib/create/compose/fontMetrics.ts. A test fails if the two drift apart.
"""
import os
import re
import site
import sys

sys.path.append(site.getusersitepackages())

from fontTools.ttLib import TTFont  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'src', 'lib', 'design', 'typefaces.ts')
OUT = os.path.join(ROOT, 'src', 'lib', 'create', 'compose', 'fontMetrics.ts')

# Basic Latin, Latin-1 letters and the punctuation and currency real copy uses.
CHARS = (
    [chr(c) for c in range(0x20, 0x7F)]
    + [chr(c) for c in range(0xA1, 0x100)]
    + list('–—‘’“”…•·₦₵€')
)
CHARS = list(dict.fromkeys(CHARS))


def faces():
    text = open(SOURCE, encoding='utf-8').read()
    body = text[text.index('export const TYPEFACES'):]
    for m in re.finditer(r"key: '([a-z]+)'.*?files: \{([^}]*)\}", body, re.S):
        for w, path in re.findall(r"(\d+): '([^']+)'", m.group(2)):
            yield m.group(1), int(w), path


def measure(path):
    font = TTFont(os.path.join(ROOT, 'public', path.lstrip('/')))
    upm = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    widths = []
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        widths.append(round(hmtx[glyph][0] * 1000 / upm) if glyph else -1)
    return widths


def main():
    rows = []
    for key, weight, path in faces():
        rows.append((f'{key}-{weight}', measure(path)))
    if not rows:
        sys.exit('No typefaces found in typefaces.ts')
    chars = ''.join(CHARS).replace('\\', '\\\\').replace("'", "\\'")
    lines = [
        '// GENERATED by scripts/build-font-metrics.py from the shipped font files.',
        '// Do not edit by hand: run `python -I scripts/build-font-metrics.py`.',
        '//',
        '// Advance widths in thousandths of an em, in the order of METRIC_CHARS.',
        '// -1 means the face has no glyph for that character.',
        '',
        f"export const METRIC_CHARS = '{chars}';",
        '',
        'export const METRIC_WIDTHS: Record<string, number[]> = {',
    ]
    for name, widths in rows:
        lines.append(f"  '{name}': [{','.join(str(w) for w in widths)}],")
    lines += ['};', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {len(rows)} faces x {len(CHARS)} characters to {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
