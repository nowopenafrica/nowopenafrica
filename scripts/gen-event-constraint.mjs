// Generate the analytics_events integrity migration FROM the TypeScript union.
//
// WHY GENERATED RATHER THAN HAND-WRITTEN
//
// The event vocabulary has to exist in two places — `EventName` in
// telemetry.ts, which makes a typo a compile error, and a CHECK constraint in
// Postgres, which is the only thing that stops a forged event with the public
// anon key.
//
// Two hand-maintained copies of the same list drift. The drift is silent and
// it fails in the worst direction: a new event passes typecheck, ships, and is
// then rejected by the database at runtime inside a `try {} catch {}` that
// telemetry deliberately swallows. The event simply never arrives, and nothing
// says so.
//
// So one list, one generator, and a test (src/test/eventIntegrity.test.ts)
// that fails if the migration and the union disagree.
//
//   node scripts/gen-event-constraint.mjs          # write the migration
//   node scripts/gen-event-constraint.mjs --check  # verify, change nothing
//
// WHAT THE MIGRATION DOES NOT DO
//
// Rate limiting. It belongs at the edge, not in a row trigger: a per-insert
// COUNT over a growing table is a self-inflicted performance problem, and an
// attacker with the anon key can afford to be patient. This closes the two
// holes SQL can actually close — an unknown event name, and an event
// attributed to somebody else.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const TELEMETRY = 'src/lib/telemetry.ts';
const MIGRATION = 'supabase/migrations/20260908120000_analytics_event_integrity.sql';

/** The declared vocabulary, read from the union itself. */
export function declaredEvents() {
  const src = readFileSync(TELEMETRY, 'utf8');
  const start = src.indexOf('export type EventName =');
  if (start < 0) throw new Error('EventName union not found in ' + TELEMETRY);

  // Line by line to the terminating member. The union is heavily commented and
  // one comment contains a semicolon, so scanning to the first `;` stops four
  // events in — a mistake already made once, in the test for this same list.
  const names = [];
  for (const line of src.slice(start).split('\n')) {
    const m = /^\s*\|\s*'([a-z0-9_]+)'/.exec(line);
    if (m) names.push(m[1]);
    if (/'\s*;\s*$/.test(line)) break;
  }
  if (names.length < 15) throw new Error(`only parsed ${names.length} events — parser is wrong`);
  return names;
}

function migrationSql(names) {
  const list = names.map((n) => `    '${n}'`).join(',\n');
  return `-- Analytics event integrity.
--
-- GENERATED by scripts/gen-event-constraint.mjs from the EventName union in
-- src/lib/telemetry.ts. Do not edit by hand — regenerate.
--
-- WHY THIS EXISTS
--
-- Measured on production 2026-09-08:
--
--   analytics_events CHECK constraints : NONE
--   INSERT policy                      : roles={anon,authenticated} WITH CHECK (true)
--
-- So the public anon key could insert unlimited rows with any name, any
-- business_id and any user_id. While the table was only a log that nothing
-- acted on, that was low-stakes. It stops being low-stakes the moment anything
-- ranks businesses on engagement, detects demand from searches, or targets
-- acquisition from it — all of which have obvious commercial motive to forge.
--
-- Two holes are closed here, and only two, because these are the two SQL can
-- close honestly:
--
--   1. An event name outside the declared vocabulary.
--   2. An event attributed to a user who did not send it.
--
-- Rate limiting is deliberately NOT attempted in a trigger; a per-insert COUNT
-- over a growing table is a self-inflicted performance problem. That belongs
-- at the edge.

-- ---------------------------------------------------------------------------
-- 1. Only declared events.
-- ---------------------------------------------------------------------------
-- NOT VALID first: the constraint applies to every new row immediately, while
-- the existing ${'${rows}'} rows are checked separately below. That ordering means a
-- slow validation can never hold a write lock on the insert path.
alter table public.analytics_events
  drop constraint if exists analytics_events_name_known;

alter table public.analytics_events
  add constraint analytics_events_name_known check (name in (
${list}
  )) not valid;

alter table public.analytics_events
  validate constraint analytics_events_name_known;

-- ---------------------------------------------------------------------------
-- 2. Props stay small.
-- ---------------------------------------------------------------------------
-- sanitizeProps already caps this client-side (12 keys, 120 chars each). This
-- is the same limit expressed where it cannot be bypassed by not using the
-- client. Generous enough that no honest event is near it.
alter table public.analytics_events
  drop constraint if exists analytics_events_props_small;

alter table public.analytics_events
  add constraint analytics_events_props_small
  check (props is null or pg_column_size(props) < 4096) not valid;

alter table public.analytics_events
  validate constraint analytics_events_props_small;

-- ---------------------------------------------------------------------------
-- 3. An event may only be attributed to the sender.
-- ---------------------------------------------------------------------------
-- The old policy was WITH CHECK (true), so an anonymous caller could write
-- events onto any account. Anonymous events stay possible — user_id NULL is
-- how the whole public directory is measured — but claiming to be somebody is
-- not.
drop policy if exists analytics_insert on public.analytics_events;

create policy analytics_insert on public.analytics_events
  for insert to anon, authenticated
  with check (user_id is null or user_id = auth.uid());

comment on constraint analytics_events_name_known on public.analytics_events is
  'Generated from the EventName union in src/lib/telemetry.ts by scripts/gen-event-constraint.mjs. Regenerate rather than editing.';
`;
}

const names = declaredEvents();
const sql = migrationSql(names).replace('${rows}', '43,596');

const check = process.argv.includes('--check');

if (check) {
  if (!existsSync(MIGRATION)) {
    console.error(`\n✗ ${MIGRATION} does not exist. Run: node scripts/gen-event-constraint.mjs\n`);
    process.exit(1);
  }
  const onDisk = readFileSync(MIGRATION, 'utf8');
  if (onDisk.trim() !== sql.trim()) {
    console.error('\n✗ The migration is out of date with the EventName union.');
    console.error('  Run: node scripts/gen-event-constraint.mjs\n');
    process.exit(1);
  }
  console.log(`✓ Migration matches the union (${names.length} events).`);
  process.exit(0);
}

writeFileSync(MIGRATION, sql, 'utf8');
console.log(`✓ Wrote ${MIGRATION} with ${names.length} events.`);
console.log('  This migration is NOT applied. See audits/NOWOPEN_APPLY_RUNBOOK.md.');
