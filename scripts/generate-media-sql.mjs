// Generates scripts/sql/update_media_services.sql from CREATIVE_SERVICES in
// src/data/populateData.ts (single source of truth). The SQL is
// non-destructive: it repairs corrupted em-dash titles, sets
// type-appropriate images on existing rows (matched by provider-name
// prefix), and inserts any services that don't exist yet.
//
// Usage: node scripts/generate-media-sql.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const source = readFileSync(join(root, 'src', 'data', 'populateData.ts'), 'utf8');
const match = source.match(/const CREATIVE_SERVICES = \[([\s\S]*?)\n\];/);
if (!match) throw new Error('Could not find CREATIVE_SERVICES in populateData.ts');

const services = eval(`[${match[1]}]`);
const pexels = (id) =>
  `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=640`;

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
// Stable ASCII prefix before the em-dash — matches rows whether or not
// their dash got mojibake'd by the earlier seeding
const prefix = (title) => title.split('—')[0].trim();

const lines = [
  '-- Repairs and enriches the media_services marketplace rows.',
  '-- Generated by scripts/generate-media-sql.mjs — do not edit by hand.',
  '-- Non-destructive and safe to re-run:',
  "--   1. fixes titles corrupted to 'â€”' by an earlier seeding",
  '--   2. sets a realistic, type-appropriate image on each known service',
  '--   3. inserts newer services that are not in the table yet',
  '',
  "UPDATE media_services SET title = replace(title, 'â€”', '—') WHERE title LIKE '%â€”%';",
  "UPDATE media_services SET description = replace(description, 'â€”', '—') WHERE description LIKE '%â€”%';",
  '',
];

for (const s of services) {
  const url = q(pexels(s.img));
  lines.push(
    `UPDATE media_services SET image_url = ${url}, thumbnail_url = ${url} WHERE title LIKE ${q(prefix(s.title) + '%')};`
  );
}

lines.push('');
for (const s of services) {
  lines.push(
    `INSERT INTO media_services (title, description, service_type, pricing, pricing_model, delivery_time, clients_served, review_count, rating, image_url, thumbnail_url, status)`,
    `SELECT ${q(s.title)}, ${q(s.description)}, ${q(s.service_type)}, ${s.pricing}, ${q(s.pricing_model)}, ${q(s.delivery_time)}, ${s.clients_served}, ${s.review_count}, ${s.rating}, ${q(pexels(s.img))}, ${q(pexels(s.img))}, 'open'`,
    `WHERE NOT EXISTS (SELECT 1 FROM media_services WHERE title LIKE ${q(prefix(s.title) + '%')});`,
    ''
  );
}

const out = join(root, 'scripts', 'sql', 'update_media_services.sql');
writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`Wrote ${out} (${services.length} services)`);
