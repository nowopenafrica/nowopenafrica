/**
 * Turn a prospect CSV into an idempotent seed migration.
 *
 * Kept in the repo rather than run as a one-off, because the 500 is the first
 * batch and the next one is 5,000. Re-running the generated migration updates
 * the same rows instead of creating a second copy of every business — the
 * conflict target is `external_id`, the source's own record id.
 *
 * It refuses to emit anything that would misrepresent a record: contact details
 * and opening hours are dropped even if the CSV carries them, because a
 * synthetic row must not appear reachable, and data_status is forced rather
 * than trusted from the file.
 *
 *   node scripts/build-seed-migration.mjs <csv> <out.sql> [dataStatus]
 */

import { readFileSync, writeFileSync } from 'node:fs';

const [, , csvPath, outPath, dataStatusArg] = process.argv;
if (!csvPath || !outPath) {
  console.error('usage: build-seed-migration.mjs <csv> <out.sql> [dataStatus]');
  process.exit(1);
}

const DATA_STATUS = dataStatusArg || 'synthetic_unverified';
const ALLOWED = ['synthetic_unverified', 'imported_authorized', 'submitted', 'admin_curated'];
if (!ALLOWED.includes(DATA_STATUS)) {
  console.error(`dataStatus must be one of ${ALLOWED.join(', ')}`);
  process.exit(1);
}

/** Minimal RFC4180 reader — the descriptions contain commas inside quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  const src = text.replace(/^﻿/, '').replace(/\r\n/g, '\n');
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (quoted) {
      if (c === '"') {
        if (src[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows
    .filter((r) => r.length === header.length && r.some((v) => v !== ''))
    .map((r) => Object.fromEntries(header.map((h, i) => [h.trim(), r[i]])));
}

const q = (v) => (v === undefined || v === null || String(v).trim() === ''
  ? 'NULL'
  : `'${String(v).trim().replace(/'/g, "''")}'`);

const rows = parseCsv(readFileSync(csvPath, 'utf8'));
if (!rows.length) { console.error('no rows'); process.exit(1); }

// Fail loudly on anything that would collide once inserted.
const slugs = new Set(), ids = new Set();
for (const r of rows) {
  if (!r.business_name?.trim() || !r.category?.trim()) {
    console.error(`row ${r.id}: name and category are required`); process.exit(1);
  }
  if (slugs.has(r.slug)) { console.error(`duplicate slug ${r.slug}`); process.exit(1); }
  if (ids.has(r.id)) { console.error(`duplicate id ${r.id}`); process.exit(1); }
  slugs.add(r.slug); ids.add(r.id);
}

const values = rows.map((r) => {
  // City is what Discover filters on; the fuller string goes in address.
  const location = r.city?.trim() || r.state?.trim() || null;
  const address = r.address?.trim() || null;
  return '  (' + [
    q(r.id), q(r.slug), q(r.business_name), q(r.category), q(location), q(address),
    q(r.description), q(r.source || 'NowOpen Africa prospect seed'), q(r.source_url),
  ].join(', ') + ')';
}).join(',\n');

const sql = `/*
  # Prospect seed — ${rows.length} records, data_status '${DATA_STATUS}'

  GENERATED by scripts/build-seed-migration.mjs from
  ${csvPath.split(/[\\/]/).pop()}. Do not hand-edit; regenerate.

  These are prospect shells, not verified businesses. They carry no phone,
  email, website, coordinates or opening hours, because those facts are not
  known — inventing them is what turns a directory into a liability.

  ${DATA_STATUS === 'synthetic_unverified' ? `They are SYNTHETIC: fabricated names for businesses that do not exist,
  used to build and exercise the claim engine. The generated is_listable
  column keeps every one of them out of public discovery, search and the
  sitemap until a real owner claims it. Nothing here overrides that.` : `Imported under an authorized source licence. Provenance is recorded on
  every row and must stay accurate.`}

  Idempotent: ON CONFLICT (external_id) updates the same row, so re-running
  never creates a second copy. Fields an owner may have edited after claiming
  are left alone — the WHERE clause skips claimed rows entirely.
*/

-- The importer is self-sufficient about the columns it writes, so a seed batch
-- can be applied to a database that predates them.
ALTER TABLE public.businesses ADD COLUMN IF NOT EXISTS address text;

INSERT INTO public.businesses (
  external_id, username, name, category, location, address, description,
  source_name, source_url,
  data_status, claim_status, verification_status, lifecycle_status,
  source_license, source_imported_at
)
SELECT v.external_id, v.username, v.name, v.category, v.location, v.address, v.description,
       v.source_name, v.source_url,
       '${DATA_STATUS}', 'unclaimed', 'unverified', 'active',
       ${DATA_STATUS === 'synthetic_unverified'
         ? `'Synthetic data generated for NowOpen Africa. Not derived from any third-party directory.'`
         : `'Imported under an authorized source licence.'`},
       now()
  FROM (VALUES
${values}
  ) AS v(external_id, username, name, category, location, address, description, source_name, source_url)
-- The index predicate is required: idx_businesses_external_id is partial
-- (WHERE external_id IS NOT NULL), and inference only matches a partial index
-- when the statement repeats its predicate.
ON CONFLICT (external_id) WHERE external_id IS NOT NULL DO UPDATE
   SET name        = EXCLUDED.name,
       category    = EXCLUDED.category,
       location    = EXCLUDED.location,
       address     = EXCLUDED.address,
       description = EXCLUDED.description,
       source_last_checked_at = now()
 WHERE public.businesses.claim_status <> 'claimed';
`;

writeFileSync(outPath, sql, 'utf8');
console.log(`wrote ${outPath}: ${rows.length} rows, data_status=${DATA_STATUS}`);
